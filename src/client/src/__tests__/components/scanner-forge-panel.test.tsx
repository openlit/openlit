import { readFileSync } from "fs";
import { join } from "path";
import { act, fireEvent, render, renderHook, screen, waitFor } from "@testing-library/react";
import { toast } from "sonner";
import ScannerForgePanel, {
	useScannerForgeRun,
} from "@/components/(playground)/scanner/scanner-forge-panel";
import { parseForgeSkill } from "@/lib/platform/connectors/scanner/forge-skill";
import type { ScannerForgeRun } from "@/lib/platform/connectors/scanner/types";
import {
	SCANNER_FORGE_COPIED,
	SCANNER_FORGE_COPIED_LABEL,
	SCANNER_FORGE_COPY,
	SCANNER_FORGE_COPY_FAILED,
	SCANNER_FORGE_EMPTY_TITLE,
	SCANNER_FORGE_RAW,
	SCANNER_FORGE_REGENERATE,
	SCANNER_FORGE_RUN,
	SCANNER_FORGE_RUNNING_TITLE,
	SCANNER_FORGE_STALE_TITLE,
	CANCEL,
} from "@/constants/messages/en";

jest.mock("sonner", () => ({
	toast: { success: jest.fn(), error: jest.fn() },
}));

jest.mock("@/components/common/markdown", () => ({
	__esModule: true,
	default: ({ content }: { content: string }) => <div data-testid="markdown">{content}</div>,
}));

class ResizeObserverMock {
	observe() {}
	unobserve() {}
	disconnect() {}
}
Object.defineProperty(global, "ResizeObserver", { writable: true, value: ResizeObserverMock });

const CONTENT = readFileSync(join(__dirname, "../fixtures/trustabl/forge-skill.md"), "utf8");
const RUN: ScannerForgeRun = {
	id: "forge:1",
	status: "succeeded",
	target: "https://github.com/anthropics/claude-agent-sdk-demos",
	policies: ["claude_sdk", "mcp"],
	policySource: { kind: "analyzer", jobId: "job:1", scannedAt: "2026-11-09T10:45:45.000Z" },
	fileName: "SKILL.md",
	startedAt: "2026-11-10T11:32:08.000Z",
	durationMs: 2300,
	cliVersion: "v0.1.8",
	command: "trustabl forge --policy claude_sdk,mcp",
	summary: parseForgeSkill(CONTENT),
};
const DETAIL: ScannerForgeRun = { ...RUN, content: CONTENT };

type PanelProps = Parameters<typeof ScannerForgePanel>[0];

function renderPanel(over: Partial<PanelProps> = {}) {
	const props: PanelProps = {
		runs: [RUN],
		selectedRun: RUN,
		onSelectRun: jest.fn(),
		onCancel: jest.fn(),
		prefillPolicies: ["claude_sdk", "mcp"],
		onRunForge: jest.fn(),
		onRegenerate: jest.fn(),
		detail: DETAIL,
		check: { status: "current", message: "up to date", checkedAt: "2026-11-10T11:33:00.000Z" },
		loadingDetail: false,
		...over,
	};
	render(<ScannerForgePanel {...props} />);
	return props;
}

function setClipboard(writeText: jest.Mock | undefined) {
	Object.defineProperty(navigator, "clipboard", {
		configurable: true,
		value: writeText ? { writeText } : undefined,
	});
}

beforeEach(() => {
	jest.clearAllMocks();
});

describe("ScannerForgePanel", () => {
	it("shows the empty state with the Analyzer policies", () => {
		const props = renderPanel({ runs: [], selectedRun: undefined, detail: undefined, check: undefined });
		expect(screen.getByText(SCANNER_FORGE_EMPTY_TITLE)).toBeInTheDocument();
		expect(screen.getByText(/claude_sdk, mcp/)).toBeInTheDocument();
		fireEvent.click(screen.getByRole("button", { name: SCANNER_FORGE_RUN }));
		expect(props.onRunForge).toHaveBeenCalled();
	});

	it("shows the running state with the command and Cancel", () => {
		const props = renderPanel({
			forging: {
				startedAt: Date.now(),
				policies: ["claude_sdk", "mcp"],
				policySource: { kind: "manual" },
				command: "trustabl forge --policy claude_sdk,mcp",
			},
		});
		expect(screen.getByText(SCANNER_FORGE_RUNNING_TITLE)).toBeInTheDocument();
		expect(screen.getByText(/\$ trustabl forge --policy claude_sdk,mcp/)).toBeInTheDocument();
		expect(screen.getByText("0:00")).toBeInTheDocument();
		fireEvent.click(screen.getByRole("button", { name: CANCEL }));
		expect(props.onCancel).toHaveBeenCalled();
	});

	it("shows stats, outline and the raw skill", () => {
		renderPanel();
		expect(screen.getByText(/generated by Trustabl Forge v0\.1\.8$/)).toBeInTheDocument();
		expect(screen.getByText("75")).toBeInTheDocument();
		expect(screen.getAllByRole("button", { name: /Tool Rules\s*24/ })[0]).toBeInTheDocument();
		fireEvent.click(screen.getByRole("tab", { name: SCANNER_FORGE_RAW }));
		expect(screen.getByText(/name: trustabl-pre-coding/).tagName).toBe("PRE");
	});

	it("copies the skill and shows Copied", async () => {
		const writeText = jest.fn().mockResolvedValue(undefined);
		setClipboard(writeText);
		renderPanel();
		fireEvent.click(screen.getByRole("button", { name: SCANNER_FORGE_COPY }));
		await waitFor(() => expect(toast.success).toHaveBeenCalledWith(SCANNER_FORGE_COPIED));
		expect(writeText).toHaveBeenCalledWith(CONTENT);
		expect(screen.getByRole("button", { name: SCANNER_FORGE_COPIED_LABEL })).toBeInTheDocument();
	});

	it("reports a failed copy", async () => {
		setClipboard(jest.fn().mockRejectedValue(new Error("denied")));
		renderPanel();
		fireEvent.click(screen.getByRole("button", { name: SCANNER_FORGE_COPY }));
		await waitFor(() => expect(toast.error).toHaveBeenCalledWith(SCANNER_FORGE_COPY_FAILED));
	});

	it("reports a missing clipboard", async () => {
		setClipboard(undefined);
		renderPanel();
		fireEvent.click(screen.getByRole("button", { name: SCANNER_FORGE_COPY }));
		await waitFor(() => expect(toast.error).toHaveBeenCalledWith(SCANNER_FORGE_COPY_FAILED));
	});

	it("shows the stale banner and regenerates", () => {
		const message = "outdated: generated from 9eca09d, current rules are 3f9c1e2";
		const props = renderPanel({
			check: { status: "stale", message, checkedAt: "2026-11-10T11:33:00.000Z" },
		});
		expect(screen.getByText(SCANNER_FORGE_STALE_TITLE)).toBeInTheDocument();
		expect(screen.getByText(new RegExp(message))).toBeInTheDocument();
		fireEvent.click(screen.getAllByRole("button", { name: SCANNER_FORGE_REGENERATE })[0]);
		expect(props.onRegenerate).toHaveBeenCalledWith(RUN);
	});

	it("shows a run still going on the server as running, without Cancel", () => {
		const running: ScannerForgeRun = { ...RUN, status: "running", summary: undefined };
		renderPanel({ runs: [running], selectedRun: running, detail: undefined, check: undefined });
		expect(screen.getByText(SCANNER_FORGE_RUNNING_TITLE)).toBeInTheDocument();
		expect(screen.getByText("$ trustabl forge --policy claude_sdk,mcp")).toBeInTheDocument();
		expect(screen.queryByRole("button", { name: CANCEL })).not.toBeInTheDocument();
	});

	it("shows a failed run's error", () => {
		const failed: ScannerForgeRun = { ...RUN, status: "failed", error: "unknown category", summary: undefined };
		renderPanel({ runs: [failed], selectedRun: failed, detail: undefined, check: undefined });
		expect(screen.getByText("unknown category")).toBeInTheDocument();
	});
});

describe("useScannerForgeRun", () => {
	const fetchMock = jest.fn();

	beforeEach(() => {
		fetchMock.mockReset();
		global.fetch = fetchMock as unknown as typeof fetch;
	});

	it("loads the run and then its check", async () => {
		fetchMock
			.mockResolvedValueOnce({ ok: true, json: async () => ({ run: DETAIL }) })
			.mockResolvedValueOnce({
				ok: true,
				json: async () => ({ check: { status: "current", message: "up to date", checkedAt: "x" } }),
			});
		const { result } = renderHook(() => useScannerForgeRun("scanner:1", RUN));
		await waitFor(() => expect(result.current.check?.status).toBe("current"));
		expect(result.current.detail?.content).toBe(CONTENT);
		expect(fetchMock.mock.calls[0][0]).toBe("/api/scanners/scanner%3A1/forge/forge%3A1");
		expect(fetchMock.mock.calls[1][0]).toBe("/api/scanners/scanner%3A1/forge/forge%3A1/check");
	});

	it("skips runs that did not succeed", async () => {
		const { result } = renderHook(() =>
			useScannerForgeRun("scanner:1", { ...RUN, status: "failed" })
		);
		await act(async () => undefined);
		expect(fetchMock).not.toHaveBeenCalled();
		expect(result.current.loading).toBe(false);
	});

	it("reports a load error", async () => {
		fetchMock.mockResolvedValueOnce({ ok: false, json: async () => "Forge run not found." });
		const { result } = renderHook(() => useScannerForgeRun("scanner:1", RUN));
		await waitFor(() => expect(result.current.error).toBe("Forge run not found."));
	});
});
